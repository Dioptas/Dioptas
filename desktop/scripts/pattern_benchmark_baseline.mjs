import { execFileSync } from "node:child_process";
import { writeFile, unlink } from "node:fs/promises";
export const baselineRevision = "d4efd68a";
/** Reconstruct the merged Canvas component with timing hooks; no permanent copy. */
export async function preparePatternBaseline() {
  const file = new URL("../src/__CanvasBaseline.tsx", import.meta.url);
  let source = execFileSync(
    "git",
    ["show", `${baselineRevision}:desktop/src/PatternView.tsx`],
    { cwd: new URL("../", import.meta.url), encoding: "utf8" },
  );
  source = source
    .replace(
      "  regionsUpdating = false,",
      "  regionsUpdating = false,\n  onRender,",
    )
    .replace(
      "  pattern: Pattern;",
      "  onRender?: (sample: {cpuMs:number;renderer:string;xMin:number;xMax:number})=>void;\n  pattern: Pattern;",
    )
    .replace(
      "  const [size, setSize]",
      "  const renderObserver = useRef(onRender);\n  renderObserver.current = onRender;\n  const [size, setSize]",
    )
    .replace(
      '    const context = canvas.current?.getContext("2d");',
      '    const started = performance.now();\n    const context = canvas.current?.getContext("2d");',
    )
    .replace(
      "    setAxisAnnotation(!!yAxis.annotation);",
      "    if(axisAnnotation !== !!yAxis.annotation) setAxisAnnotation(!!yAxis.annotation);",
    )
    .replace(
      "    setLeft(Math.max(64, Math.ceil(tickWidth) + 44));",
      "    const nextLeft = Math.max(64, Math.ceil(tickWidth) + 44);\n    if(nextLeft !== left) setLeft(nextLeft);",
    );
  // Adapt historical legend calls to the shared positioning contract. The
  // historical curve renderer and geometry remain unchanged.
  source = source
    .replaceAll(
      "<IntegrationPhaseLegend",
      "<IntegrationPhaseLegend bounds={{left,top,width:w,height:h}}",
    )
    .replaceAll(
      "<OverlayPlotLegend",
      "<OverlayPlotLegend bounds={{left,top,width:w,height:h}}",
    );
  const end = source.indexOf(
    "  }, [\n    pattern,",
    source.indexOf("const curveKey"),
  );
  if (end < 0) throw Error("Baseline timing insertion point not found");
  source =
    source.slice(0, end) +
    '    renderObserver.current?.({cpuMs:performance.now()-started,renderer:"canvas2d",xMin:xmin,xMax:xmax});\n' +
    source.slice(end);
  await writeFile(
    file,
    "// Generated by pattern_benchmark_baseline.mjs; do not edit.\n" + source,
  );
  return async () => {
    await unlink(file).catch(() => {});
  };
}
